"""Export reviewed web UI tests as a local Playwright pytest suite."""
import io
import json
import re
import zipfile

from models.web_testing import WebUITestPlan


def _locator_expression(locator) -> str:
    value = json.dumps(locator.value, ensure_ascii=True)
    if locator.strategy == "role":
        return f"page.get_by_role({json.dumps(locator.role)}, name={value}, exact=True)"
    if locator.strategy == "label":
        return f"page.get_by_label({value}, exact=True)"
    if locator.strategy == "placeholder":
        return f"page.get_by_placeholder({value}, exact=True)"
    return f"page.get_by_text({value}, exact=True)"


def _test_name(test_case) -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", test_case.title.lower()).strip("_")[:60]
    identifier = test_case.test_case_id.lower().replace("-", "_")
    return f"test_{identifier}_{slug or 'web_ui'}"


def export_playwright_pytest(plan: WebUITestPlan) -> bytes:
    lines = [
        '"""Generated by TestGen AI. Review assertions and test data before running."""',
        "from playwright.sync_api import Page, expect",
        "",
        f"BASE_URL = {json.dumps(plan.url, ensure_ascii=True)}",
        "",
    ]
    for case in plan.test_cases:
        lines.extend([
            f"def {_test_name(case)}(page: Page):",
            f"    # Preconditions: {'; '.join(item.replace(chr(10), ' ').replace(chr(13), ' ') for item in case.preconditions) or 'Page is ready'}",
            '    page.goto(BASE_URL, wait_until="domcontentloaded")',
        ])
        for action in case.actions:
            target = _locator_expression(action.locator)
            if action.action == "click":
                lines.append(f"    {target}.click()")
            elif action.action == "fill":
                lines.append(f"    {target}.fill({json.dumps(action.value, ensure_ascii=True)})")
            elif action.action == "check":
                lines.append(f"    {target}.check()")
            elif action.action == "uncheck":
                lines.append(f"    {target}.uncheck()")
            elif action.action == "select_option":
                lines.append(f"    {target}.select_option(label={json.dumps(action.value, ensure_ascii=True)})")
        for assertion in case.assertions:
            if assertion.kind == "url_contains":
                lines.append(f"    assert {json.dumps(assertion.value, ensure_ascii=True)} in page.url")
                continue
            target = _locator_expression(assertion.locator)
            if assertion.kind == "visible":
                lines.append(f"    expect({target}).to_be_visible()")
            elif assertion.kind == "hidden":
                lines.append(f"    expect({target}).to_be_hidden()")
            elif assertion.kind == "contains_text":
                lines.append(f"    expect({target}).to_contain_text({json.dumps(assertion.value, ensure_ascii=True)})")
        lines.append("")

    readme = f"""# Generated web UI tests

Target page: {plan.url}
Page title at inspection: {plan.page_title or 'Not available'}

Review every action, locator, assertion and test value before running. The site may
have changed since inspection. These tests are generated drafts and have not been
executed by TestGen AI. Use only an application and environment you are authorized
to test; replace sample values with safe test data.

## Run locally

1. Create and activate a virtual environment.
2. Install dependencies: `python -m pip install -r requirements.txt`
3. Install browser binaries: `python -m playwright install chromium`
4. Run: `python -m pytest -v`
"""
    stream = io.BytesIO()
    with zipfile.ZipFile(stream, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("test_web_ui.py", "\n".join(lines))
        archive.writestr("requirements.txt", "pytest>=8,<10\nplaywright>=1.50,<2\n")
        archive.writestr("README.md", readme)
    return stream.getvalue()